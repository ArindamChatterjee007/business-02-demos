import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { resolve, join, dirname } from "node:path";
import { pathToFileURL } from "node:url";
import { createHash } from "node:crypto";
import { chromium } from "@playwright/test";
import ExcelJS from "exceljs";
import { syntheticForm } from "./pdf-fixtures.mjs";

const target = resolve(process.argv[2] || "");
if (!process.argv[2] || !target.endsWith("form-desk.html")) throw new Error("Pass the generated form-desk.html path.");
const directory = dirname(target);
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ acceptDownloads: true, viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
const externalRequests = [];
page.on("pageerror", error => errors.push(error.message));
page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
await page.route(/^https?:\/\//, route => { externalRequests.push(new URL(route.request().url()).origin); return route.abort(); });
const checks = [];
try {
  await page.goto(pathToFileURL(target).href, { waitUntil: "load" });
  await page.locator("#export:not([disabled])").waitFor();
  assert.equal(await page.locator("#results tbody tr").count(), 3);
  assert.equal(await page.locator("#results tbody tr").first().locator("td").nth(1).textContent(), "0007");
  assert.equal(await page.locator("#results tbody tr").first().locator("td").nth(3).textContent(), "=1+1");
  checks.push("Three synthetic PDFs produce exact visible rows and preserved identifiers/literal text");
  const downloadEvent = page.waitForEvent("download");
  await page.locator("#export").click();
  const download = await downloadEvent;
  const workbookPath = join(directory, "verified-demo-output.xlsx");
  await download.saveAs(workbookPath);
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.readFile(workbookPath);
  const sheet = workbook.getWorksheet("Extracted fields");
  assert.equal(sheet.rowCount, 4);
  assert.equal(sheet.getCell("B2").value, "0007");
  assert.equal(sheet.getCell("C2").value, 1250.5);
  assert.equal(sheet.getCell("D2").value, "=1+1");
  assert.equal(sheet.getCell("D2").formula, undefined);
  assert.equal(sheet.getCell("E2").value, false);
  assert.equal(sheet.getCell("C3").value, 0);
  checks.push("Downloaded XLSX reparsed with exact numbers, booleans, leading zeros and no formula execution");
  await page.locator("#invalid-sample").click();
  await page.locator("#batch-state").filter({ hasText: "Needs review" }).waitFor();
  assert.equal(await page.locator("#export").isDisabled(), true);
  assert.match(await page.locator("#checks-list").innerText(), /Invalid numeric field/);
  await page.screenshot({ path: join(directory, "error-state.png"), fullPage: true });
  checks.push("Invalid PDF amount blocks all export without a partial workbook");
  await page.locator("#load-samples").click();
  await page.locator("#export:not([disabled])").waitFor();
  await page.getByRole("tab", { name: "Field map", exact: true }).click();
  await page.getByLabel("COLUMN NAME 1", { exact: true }).fill("Customer reference");
  await page.getByLabel("COLUMN NAME 1", { exact: true }).press("Tab");
  assert.equal(await page.locator("#export").isDisabled(), true);
  await page.locator("#validate").click();
  await page.locator("#export:not([disabled])").waitFor();
  await page.getByRole("tab", { name: "Data table", exact: true }).click();
  assert.equal(await page.locator("#results th").nth(1).textContent(), "Customer reference");
  checks.push("Field-map changes invalidate stale export and revalidate into the renamed column");
  await page.locator("#load-samples").click();
  await page.locator("#export:not([disabled])").waitFor();
  for (const [width, height] of [[1440, 1000], [390, 844], [320, 740]]) {
    await page.setViewportSize({ width, height });
    const layout = await page.evaluate(() => ({
      width: innerWidth, overflow: document.documentElement.scrollWidth > innerWidth,
      imageLoaded: document.querySelector("#preview-image").naturalWidth > 0,
      buttons: [...document.querySelectorAll("button")].filter(button => button.getClientRects().length).map(button => ({ text: button.textContent.trim(), overflow: button.scrollWidth > button.clientWidth + 2 })),
    }));
    assert.equal(layout.width, width);
    assert.equal(layout.overflow, false, `Page overflow at ${width}`);
    assert.equal(layout.imageLoaded, true);
    assert.deepEqual(layout.buttons.filter(button => button.overflow), [], `Button text overflow at ${width}`);
    await page.screenshot({ path: join(directory, `form-desk-${width}.png`), fullPage: true });
    await page.getByRole("tab", { name: "Field map", exact: true }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.getByRole("tab", { name: "Data table", exact: true }).click();
  }
  checks.push("1440/390/320 CSS viewports fit without page/button overflow and source bitmap loads");
  await page.locator("#clear").click();
  assert.equal(await page.locator("#file-list .file-row").count(), 0);
  assert.equal(await page.locator("#results tbody tr").count(), 0);
  assert.equal(await page.locator("#export").isDisabled(), true);
  assert.equal(await page.locator("#preview-image").getAttribute("src"), null);
  const bytes = await syntheticForm({ id: "0020", amount: "7.25", notes: "<img src=x onerror=alert(1)>" });
  const fingerprint = createHash("sha256").update(bytes).digest("hex");
  await page.locator("#pdf-files").setInputFiles({ name: "selected-local.pdf", mimeType: "application/pdf", buffer: Buffer.from(bytes) });
  await page.locator("#validate:not([disabled])").waitFor();
  await page.locator("#validate").click();
  await page.locator("#export:not([disabled])").waitFor();
  assert.equal(await page.locator("#results tbody tr").count(), 1);
  assert.equal(await page.locator("#results tbody tr td").nth(3).textContent(), "<img src=x onerror=alert(1)>");
  assert.equal(await page.locator("#results img").count(), 0);
  assert.equal(createHash("sha256").update(bytes).digest("hex"), fingerprint);
  await page.locator("#pdf-files").setInputFiles({ name: "selected-local.pdf", mimeType: "application/pdf", buffer: Buffer.from(bytes) });
  await page.locator("#status").filter({ hasText: "Duplicate source filename" }).waitFor();
  assert.equal(await page.locator("#file-list .file-row").count(), 1);
  checks.push("Explicit local file selection, duplicate rejection, text-safe rendering and source hash preservation");
  await page.locator("#clear").click();
  await page.getByRole("tab", { name: "Field map", exact: true }).click();
  await page.locator("#map-file").setInputFiles({ name: "invalid.json", mimeType: "application/json", buffer: Buffer.from('{"wrong":true}') });
  await page.locator("#status").filter({ hasText: "Invalid field-map structure" }).waitFor();
  await page.getByRole("tab", { name: "Field map", exact: true }).focus();
  await page.keyboard.press("ArrowRight");
  assert.equal(await page.getByRole("tab", { name: /^Checks/ }).getAttribute("aria-selected"), "true");
  checks.push("Invalid map import fails safely and tab keyboard navigation works");
  assert.deepEqual(externalRequests, []);
  assert.deepEqual(errors, []);
  const report = { checkedAt: new Date().toISOString(), status: "PASS", demoOnly: true, checks, externalRequests, errors, testedViewports: [1440, 390, 320], workbookSHA256: createHash("sha256").update(await readFile(workbookPath)).digest("hex"), noServer: true, continuousPolling: false, note: "Synthetic workflow proof, not client delivery or arbitrary-PDF/OCR certification." };
  await writeFile(join(directory, "verification.json"), JSON.stringify(report, null, 2));
  console.log(JSON.stringify({ ...report, directory }, null, 2));
} finally { await context.close(); await browser.close(); }